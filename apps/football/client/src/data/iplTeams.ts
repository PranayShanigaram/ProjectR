/** Deterministic hash from player name for stable variance */
function nameHash(name: string): number {
  let h = 0;
  for (let i = 0; i < name.length; i++) {
    h = ((h << 5) - h + name.charCodeAt(i)) | 0;
  }
  return Math.abs(h);
}

function clamp(val: number, min: number, max: number): number {
  return Math.max(min, Math.min(max, val));
}

/** Get batting & bowling ability for any player.
 *  Uses explicit ratings; falls back to role-based defaults for unknown players. */
export function getPlayerAbilities(player: Player): { bat: number; bowl: number } {
  const known = PLAYER_ABILITIES[player.name];
  if (known) return known;

  // Fallback for any player not in the map (shouldn't happen now)
  const v = (nameHash(player.name) % 15) - 7;

  switch (player.role) {
    case 'batsman':
      return { bat: clamp(60 + v, 45, 75), bowl: clamp(15 + (v >> 1), 5, 25) };
    case 'bowler':
      return { bat: clamp(20 + (v >> 1), 8, 30), bowl: clamp(60 + v, 45, 75) };
    case 'all-rounder':
      return { bat: clamp(50 + v, 38, 65), bowl: clamp(50 + v, 38, 65) };
    case 'wicket-keeper':
      return { bat: clamp(58 + v, 45, 72), bowl: clamp(10 + (v >> 2), 5, 18) };
  }
}

